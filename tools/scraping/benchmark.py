#!/usr/bin/env python3
"""Offline corpus benchmark. Never execute snapshot scripts or follow page/media URLs."""
import argparse, hashlib, html, json, os, re, statistics, time, tracemalloc
from pathlib import Path
from urllib.parse import urljoin
os.environ.setdefault('CRAWL4_AI_BASE_DIRECTORY', str(Path('/tmp/kino-crawl4ai')))
from bs4 import BeautifulSoup
from scrapling import Selector
from crawl4ai import JsonCssExtractionStrategy
from importlib.metadata import version

INPUTS = {'tvmas': ('Markdown pegado.md','https://rojadirectatvmas.net/'), 'eu': ('Texto pegado (2).txt','http://www.rojadirecta.eu/'), 'kim': ('Texto pegado (3).txt','https://rojadirecta.kim/')}
# Hand-audited fields in the supplied captures, not generated by a scraper.
GOLD = {
 'tvmas': [{'title':'Telemundo','page':'https://rojadirectatvmas.net/en-vivo/telemundo'}, {'title':'TYC Sports','page':'https://rojadirectatvmas.net/en-vivo/tyc-sports'}],
 'eu': [{'title':'Wuhan Open','date':'2026-10-14T05:00'}, {'title':'Track Cycling World Championships','date':'2026-10-14T12:15'}],
 'kim': [{'title':'Roma vs Real Madrid en Vivo','time':'07:00','competition':'UEFA Youth League'}, {'title':'Manchester City vs PSG en Vivo','time':'09:00','competition':'UEFA Youth League'}]
}
SELECTORS = {'tvmas':'article.card','eu':'[itemtype*="SportsEvent"]','kim':'#my-table tbody tr'}
def normalise(raw, site):
    if site == 'tvmas':
        raw=re.sub(r'\[([^\]]+)\]\((https?://[^)]+)\)', lambda m:m[2], raw)
        raw=html.unescape(raw.replace('\\<','<').replace('\\>','>').replace('\\/','/'))
        raw='\n'.join(re.sub(r'^\s*\|\s?|\s*\|\s*$', '', line) for line in raw.splitlines())
    return raw

def clean(t): return re.sub(r'\s+',' ',str(t or '')).strip()
def extraction(site, body, engine):
    # Different installed tools do the actual DOM selection/extraction.
    if engine == 'crawl4ai':
        def field(name, sel, attr=None):
            return {'name':name,'selector':sel,'type':'attribute' if attr else 'text', **({'attribute':attr} if attr else {})}
        sources=[field('provider','td:nth-of-type(2)'),field('lang','td:nth-of-type(3)'),field('type','td:nth-of-type(4)'),field('page','a[href]','href')]
        fields={
          'tvmas':[field('title','h3'),field('page','a.btn-watch[href]','href'),field('logo','img[src]','src')],
          'eu':[field('title','[itemprop="name"]'),field('date','[itemprop="startDate"]','content'), {'name':'sources','selector':'table.taboastreams tr:has(a[href])','type':'nested_list','fields':sources}],
          'kim':[field('time','td:nth-of-type(1)'),field('title','td:nth-of-type(3) a[href]'),field('cell','td:nth-of-type(3)'),field('page','td:nth-of-type(3) a[href]','href')]
        }[site]
        return JsonCssExtractionStrategy({'name':site,'baseSelector':SELECTORS[site],'fields':fields}).run(INPUTS[site][1],[body])
    if engine == 'scrapling':
        root=Selector(body, adaptive=False)
        select=lambda node,sel:node.css(sel)
        text=lambda node:node.get_all_text(separator=' ',strip=True)
        attrs=lambda node:node.attrib
    else:
        root=BeautifulSoup(body,engine)
        select=lambda node,sel:node.select(sel)
        text=lambda node:node.get_text(' ',strip=True)
        attrs=lambda node:node.attrs
    def txt(node,sel):
        found=select(node,sel); return clean(text(found[0])) if found else ''
    def attr(node,sel,key):
        found=select(node,sel); return attrs(found[0]).get(key,'') if found else ''
    out=[]
    for node in select(root,SELECTORS[site]):
        if site=='tvmas': out.append({'title':txt(node,'h3'),'page':attr(node,'a.btn-watch[href]','href'),'logo':attr(node,'img[src]','src')})
        elif site=='eu':
            sources=[]
            for row in select(node,'table.taboastreams tr'):
                page=attr(row,'a[href]','href')
                if page: sources.append({'provider':txt(row,'td:nth-of-type(2)'), 'lang':txt(row,'td:nth-of-type(3)'), 'type':txt(row,'td:nth-of-type(4)'), 'page':page})
            out.append({'title':txt(node,'[itemprop="name"]'),'date':attr(node,'[itemprop="startDate"]','content'),'sources':sources})
        else: out.append({'time':txt(node,'td:nth-of-type(1)'), 'title':txt(node,'td:nth-of-type(3) a[href]'),'cell':txt(node,'td:nth-of-type(3)'), 'page':attr(node,'td:nth-of-type(3) a[href]','href')})
    return out

def canonical(site, rows):
    out=[]
    for row in rows:
        row={k:clean(v) if k!='sources' else [{k:clean(v) for k,v in s.items()} for s in v] for k,v in row.items()}
        if not row.get('title'):continue
        if site=='kim':row['competition']=clean(row.pop('cell','').replace(row['title'],''))
        if site=='eu':
            for source in row['sources']:source['page']=urljoin(INPUTS[site][1],source['page'])
        else:row['page']=urljoin(INPUTS[site][1],row['page'])
        out.append(row)
    return out

def summary(site, rows):
    links=[s['page'] for r in rows for s in r['sources']] if site=='eu' else [r['page'] for r in rows]
    return {'records':len(rows),'source_links':len(links),'unique_links':len(set(links)),'unique_titles':len(set(r['title'] for r in rows)), 'direct_media_urls':sum(bool(re.search(r'\.(m3u8|mpd|mp4)(?:[?#]|$)',s,re.I)) for s in links)}

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--dir',type=Path,required=True);ap.add_argument('--output',type=Path,required=True);ap.add_argument('--iterations',type=int,default=8);args=ap.parse_args()
    assert args.iterations>0
    data={site:normalise((args.dir/file).read_text(encoding='utf-8'),site) for site,(file,_) in INPUTS.items()}
    result={'method':'normalisation outside timing; full DOM parse + field extraction + canonicalisation, no JS/network/media/LLM', 'versions':{n:version(n) for n in ['beautifulsoup4','lxml','scrapling','crawl4ai','playwright']}, 'corpus_sha256':{s:hashlib.sha256((args.dir/file).read_bytes()).hexdigest() for s,(file,_) in INPUTS.items()}, 'iterations':args.iterations,'tools':{}}
    for engine in ['lxml','html.parser','scrapling','crawl4ai']:
        result['tools'][engine]={}
        for site,body in data.items():
            samples=[]
            for _ in range(args.iterations):
                start=time.perf_counter();rows=canonical(site,extraction(site,body,engine));samples.append((time.perf_counter()-start)*1000)
            reference=canonical(site,extraction(site,body,'lxml'))
            altered=body.replace('class="card"','class="card extra"').replace('class="menutitle"','class="extra menutitle"').replace('<tbody>','<tbody>\n<!-- changed -->')
            broken=body.replace('card','renamed-card').replace('SportsEvent','RenamedEvent').replace('my-table','changed-table')
            tracemalloc.start();extraction(site,body,engine);_,peak=tracemalloc.get_traced_memory();tracemalloc.stop()
            row={**summary(site,rows),'median_ms':round(statistics.median(samples),2),'p95_ms':round(sorted(samples)[-1],2),'python_peak_kib':round(peak/1024,1),'equal_to_baseline_fields':rows==reference,'mutation_benign_same':canonical(site,extraction(site,altered,engine))==reference,'mutation_selector_break_records':len(canonical(site,extraction(site,broken,engine))),'network_calls':0,'llm_calls':0,'http403':'NOT_TESTED transport; only error-page extraction below', 'error_page_records':len(canonical(site,extraction(site,'<html><body>403 Forbidden</body></html>',engine))), 'manual_sample_fields_correct':sum(rows[i].get(k)==v for i,r in enumerate(GOLD[site]) for k,v in r.items()), 'manual_sample_fields_total':sum(len(r) for r in GOLD[site]),'examples':rows[:2]}
            result['tools'][engine][site]=row
            print(engine,site,row['records'],row['median_ms'],'ms','equal=',row['equal_to_baseline_fields'],flush=True)
    args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n')
if __name__=='__main__': main()
